-- =========================================================================
-- Язык интерфейса и удаление аккаунта.
--
-- Две несвязанные вещи в одной миграции по одной причине: обе про сам
-- аккаунт, а не про игру, и обе трогают только таблицу users.
-- =========================================================================

-- -------------------------------------------------------------------------
-- Язык интерфейса
-- -------------------------------------------------------------------------

-- Хранится на сервере, а не только на устройстве: выбранный язык должен
-- переезжать вместе с аккаунтом на новый телефон. Клиент дополнительно
-- кэширует его локально, чтобы нарисовать первый экран до ответа сервера
-- (см. lib/core/app_locale.dart) — но источник истины здесь.
--
-- Не native_language: родной язык игрока и язык, на котором ему удобно
-- читать меню, — разные вещи. Немец, учящий испанский с английского,
-- вполне может держать интерфейс на английском.
alter table users
  add column if not exists interface_language text not null default 'ru';

comment on column users.interface_language is
  'Язык интерфейса приложения: ru | en. Не связан с native_language — '
  'это язык меню, а не язык, с которого игрок переводит.';

-- Проверка ограничением, а не «на совести клиента»: список поддерживаемых
-- языков интерфейса короткий и растёт медленно (пока ru и en), а неизвестный
-- код тут означал бы у игрока пустые надписи на всех экранах.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'users_interface_language_check'
  ) then
    alter table users
      add constraint users_interface_language_check
      check (interface_language in ('ru', 'en'));
  end if;
end $$;

-- -------------------------------------------------------------------------
-- Удаление аккаунта
-- -------------------------------------------------------------------------

/**
 * Полностью удаляет аккаунт вызывающего игрока.
 *
 * Удаляется строка auth.users — от неё по цепочке on delete cascade уходит
 * public.users, а от неё все двенадцать таблиц с user_id (языки, кошелёк,
 * прогресс, дружбы, записи голоса, сессии). Поэтому здесь НЕ перечисляются
 * все таблицы игры: перечисление пришлось бы дополнять при каждой новой
 * таблице, и однажды забылось бы, оставив в базе осиротевшие строки.
 *
 * Руками чистятся только те ссылки, которые каскадом НЕ покрыты, потому что
 * заведены без on delete cascade:
 *   * matches.player_a_id / player_b_id / winner_id / forfeited_by — матч
 *     без одного из двух игроков не имеет смысла, поэтому матчи удаляются
 *     целиком (их раунды, оценки и записи уйдут каскадом от matches);
 *   * reports.reported_user_id — жалоба НА удалённого игрока переживает
 *     его аккаунт: она нужна модерации как факт, поэтому ссылка
 *     обнуляется, а сама жалоба остаётся.
 *
 * security definer: удалять строку в auth.users игрок сам по себе права не
 * имеет, и давать ему такое право на всю таблицу нельзя — функция удаляет
 * строго auth.uid() и ничего больше.
 */
create or replace function public.delete_account()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'not authenticated';
  end if;

  -- Порядок: сперва то, что мешает каскаду, потом сам аккаунт.
  update reports set reported_user_id = null where reported_user_id = v_uid;
  delete from matches where player_a_id = v_uid or player_b_id = v_uid;

  delete from auth.users where id = v_uid;
end;
$$;

-- Функция удаляет ровно того, кто её вызвал, поэтому её и должен вызывать
-- обычный авторизованный игрок. Анонимный вызов отсекается проверкой
-- auth.uid() внутри.
revoke all on function public.delete_account() from public;
grant execute on function public.delete_account() to authenticated;
