-- Техническая отладка пайплайна прямо в игре.
--
-- Пока причина сбоев неясна, игрок (он же разработчик) должен видеть НЕ
-- красивую подделку под оценку, а то, что на самом деле ответили ASR и
-- LLM. Нейтральные 7 баллов при молчащем судье выглядят как настоящая
-- оценка и не несут никакой информации о поломке.
--
-- Здесь только техническая диагностика; смысловые статусы живут в
-- transcript_status (0013) и judge_status (0014) и остаются главными.
-- Формат (все поля необязательные, пишутся по мере готовности):
--   {
--     "asr":   {"provider","model","elapsed_ms","status","transcript","confidence","error"},
--     "judge": {"model","elapsed_ms","status","score","errors_count","reason","raw"}
--   }
--
-- ЭТО ВРЕМЕННАЯ ДИАГНОСТИКА: столбец можно будет удалить, когда пайплайн
-- перестанет преподносить сюрпризы. Показ на экране выключается одной
-- константой kShowPipelineDebug в lib/core/debug_flags.dart.

alter table voice_recordings
  add column if not exists pipeline_debug jsonb;
