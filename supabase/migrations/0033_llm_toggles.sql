-- Два переключателя, которыми игрок сам решает, где участвует модель.
--
-- ЗАЧЕМ ЭТО НАСТРОЙКА, А НЕ ПЕРЕМЕННАЯ ОКРУЖЕНИЯ. До сих пор обоими
-- решениями управляли секреты Edge Function (JUDGE_ENABLED,
-- EXPLAIN_PREFER_DATASET). Это годится для «выключить провайдера на время
-- тестов», но не годится для игры: чтобы сравнить оценку модели с
-- поэлементной, приходилось передеплоивать функцию, а сравнить их на одном
-- аккаунте и вовсе было нельзя. Теперь выбор живёт у игрока и меняется
-- переключателем.
--
-- ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ — false у обоих, и это ровно нынешнее поведение,
-- а не новое: судья был выключен (JUDGE_ENABLED по умолчанию 0), разбор
-- брался из датасета (EXPLAIN_PREFER_DATASET по умолчанию 1). Миграция
-- ничего не меняет для тех, кто ничего не трогал, — она только даёт
-- возможность тронуть.

alter table users
  add column if not exists llm_scoring_enabled boolean not null default false,
  add column if not exists llm_explanations_enabled boolean not null default false;

comment on column users.llm_scoring_enabled is
  'Балл за раунд выставляет модель. Выключено — считается поэлементно, по '
  'тому же эталону с «|», который игрок видел на экране: балл и подсветка '
  'тогда не могут разойтись, и вызов провайдера не нужен вовсе.';

comment on column users.llm_explanations_enabled is
  'Разбор ошибок пишет модель. Выключено — берётся из датасета пояснений '
  'для языковой пары: мгновенно, без провайдера и без его лимитов. Модель '
  'остаётся страховкой там, где датасет молчит, независимо от флага.';
