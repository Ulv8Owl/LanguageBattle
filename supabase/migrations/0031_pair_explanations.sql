-- =========================================================================
-- Разбор ошибок пишет датасет, а модель осталась страховкой.
--
-- Что изменилось по сравнению с 0030. Тогда объяснение целиком приходило
-- от языковой модели, и grammar_errors.message был единственным местом,
-- где оно жило. Теперь пояснения написаны заранее и разложены по ПАРАМ
-- языков (assets/cefr/explanations/RU-EN/... и остальные пять): текст на
-- том языке, которым игрок владеет, про тот, который он учит. Клиент
-- читает их сам и в message не заглядывает, пока там пусто.
--
-- Схеме от этого нужен только новый комментарий: пустой message перестал
-- означать сбой. Для шести покрытых пар он пуст ВСЕГДА, потому что модель
-- в таком раунде не вызывается вовсе.
-- =========================================================================

comment on column grammar_errors.message is
  'Объяснение ошибки. У категории element оно приходит от модели '
  '(_shared/explainElements.ts) и ТОЛЬКО когда пару языков не покрывает '
  'датасет: для шести покрытых пар модель не вызывается, поле остаётся '
  'пустым, а текст разбора клиент берёт из assets/phrases/'
  'explain_<уровень>_<родной>-<целевой>.json. Пусто и без датасета — '
  'разбора нет ни от кого, и клиент говорит об этом прямым текстом.';

comment on column grammar_errors.replacement is
  'Правильный вариант. У категории element — текст самого элемента, '
  'который игрок должен был произнести.';
