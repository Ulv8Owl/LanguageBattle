-- Номер попытки внутри раунда, проставляемый клиентом при загрузке записи.
--
-- Раньше сервер вычислял его сам — считал записи раунда, созданные не позже
-- текущей. Это работало ровно до первой осечки: запрос счётчика ошибок не
-- возвращает, а `count ?? 1` молча превращает ЛЮБОЙ сбой во «вторую попытку
-- это первая». Видно это только по тому, что вторая попытка вдруг получает
-- подробные объяснения, которых для неё не запрашивали, — то есть никак.
--
-- Клиент номер попытки знает точно: он и так подставляет его в имя файла
-- (trainingRecordingPath). Пусть говорит прямо.
--
-- Столбец аддитивный и nullable: записи, залитые прежними сборками, остаются
-- валидными, а сервер для них откатывается к старому подсчёту.
alter table voice_recordings
  add column if not exists attempt_number smallint;

comment on column voice_recordings.attempt_number is
  'Номер попытки в раунде (1 или 2 в Одиночной Игре, 1 в PvP). NULL — запись от старого клиента.';
