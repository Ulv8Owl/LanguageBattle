-- Несказанное — отдельная категория, а не ошибка.
--
-- Мультимодальная модель отдаёт две разные вещи. Ошибка — это кусок, где
-- игрок сказал НЕ ТАК: у неё есть объяснение и исправление, и в разборе
-- она становится нажимаемой плашкой. Пропуск — это кусок правильного
-- перевода, которого игрок не сказал ВОВСЕ: объяснять там нечего, его
-- надо просто показать красным.
--
-- Смешать их в одной категории нельзя ни в какую сторону: как ошибка
-- пропуск дал бы плашку, за которой пусто, а как пропуск ошибка потеряла
-- бы разбор. Поэтому категорий две, и балл они снижают по-разному —
-- пропуски долей от длины перевода, ошибки по баллу за штуку.

alter table grammar_errors drop constraint if exists grammar_errors_category_check;
alter table grammar_errors
  add constraint grammar_errors_category_check
  check (category in ('grammar', 'spelling', 'style', 'element', 'omni', 'missing'));

comment on column grammar_errors.span_text is
  'Фрагмент речи, к которому относится строка. У категории omni это то, '
  'что игрок сказал неверно; у missing — кусок правильного перевода, '
  'который он не сказал вовсе. Смещения в эталон (offset_start/length) у '
  'обеих пусты: эталона у модели не было.';
