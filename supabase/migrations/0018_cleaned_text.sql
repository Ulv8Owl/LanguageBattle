-- Что игрок сказал, за вычетом брошенных вариантов и повторов.
--
-- Игрок часто поправляет сам себя прямо в записи: «Go to magazine. Go to
-- shop». Это нормальная живая речь, а не ошибка, поэтому судья засчитывает
-- только последний вариант. Но подсветка правки на экране строится
-- СРАВНЕНИЕМ сказанного с исправленным — и если сравнивать с исходным
-- текстом, отброшенный вариант подсветится красным, то есть ровно как
-- ошибка, которой он не является.
--
-- Поэтому судья возвращает очищенный текст отдельно, и сравнение идёт с
-- ним. Исходный transcript при этом остаётся нетронутым: в блоке
-- «Голосовое:» игрок должен видеть, что распознаватель услышал на самом
-- деле, включая самоисправления.
alter table voice_recordings
  add column if not exists cleaned_text text;
