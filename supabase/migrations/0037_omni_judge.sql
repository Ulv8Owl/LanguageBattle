-- Мультимодальная модель слушает аудио и сама решает, верно ли переведено.
--
-- ЧТО МЕНЯЕТСЯ ПО СУТИ. До сих пор путь был из двух шагов: распознавание
-- превращало речь в текст, а дальше текст сравнивался с эталоном —
-- поэлементно или моделью. Эталон был центром всей оценки.
--
-- Теперь оценивает одна модель, которая слышит речь напрямую. И судит она
-- НЕ ПО ЭТАЛОНУ: ей дают задание на родном языке игрока и запись ответа,
-- а перевод она проверяет сама — так же, как это сделал бы преподаватель,
-- который не держит перед глазами единственно верный вариант. Это важно
-- содержательно: у фразы почти всегда несколько правильных переводов, и
-- сверка с одним из них наказывала за верный ответ, сказанный иначе.
--
-- ЭТАЛОН НЕ ИСЧЕЗАЕТ. Он остаётся для подсказок: разбитая на элементы
-- фраза, которую игрок открывает по одной части, — по-прежнему ручной
-- перевод из датасета. Просто оценка на него больше не смотрит.

-- -------------------------------------------------------------------------
-- 1. Задание на родном языке — то, что видел игрок
-- -------------------------------------------------------------------------

-- Раньше серверу хватало generated_phrase (эталон на изучаемом языке): по
-- нему считали и балл, и подсветку. Модели нужно ровно обратное — текст
-- задания, а его на сервере не было вовсе. Взять его сервер сам не может:
-- банк фраз лежит в приложении, а не в базе, — поэтому присылает клиент,
-- ровно ту строку, которую показал игроку.
alter table training_rounds
  add column if not exists prompt_text text;

comment on column training_rounds.prompt_text is
  'Задание на РОДНОМ языке игрока — то, что он видел на экране и переводил. '
  'Единственное, что получает мультимодальная модель кроме самой записи: '
  'эталон ей не показывают, иначе она сверяла бы с одним вариантом вместо '
  'того, чтобы оценивать перевод.';

-- В Дуэли у игроков разные родные языки, поэтому задание не одно.
alter table rounds
  add column if not exists prompt_by_language jsonb;

comment on column rounds.prompt_by_language is
  'Задание раунда по языкам: код языка -> текст. В Дуэли соперники видят '
  'фразу каждый на своём родном, и модели нужно то задание, которое видел '
  'ИМЕННО оценваемый игрок.';

-- -------------------------------------------------------------------------
-- 2. Ошибка привязана к сказанному, а не к элементу эталона
-- -------------------------------------------------------------------------

-- offset_start/length указывали в ЭТАЛОН: разбор строился по его элементам.
-- У модели эталона нет, и границы ошибок она проводит по смыслу — «вот
-- этот кусок сказан не так». Такой кусок нечем адресовать, кроме его
-- собственного текста, поэтому текст и храним.
alter table grammar_errors
  add column if not exists span_text text;

comment on column grammar_errors.span_text is
  'Фрагмент того, что игрок СКАЗАЛ, к которому относится ошибка. Модель '
  'проводит границы по смыслу, а не по элементам эталона, поэтому смещения '
  'в эталон (offset_start/length) для таких ошибок пусты.';

alter table grammar_errors drop constraint if exists grammar_errors_category_check;
alter table grammar_errors
  add constraint grammar_errors_category_check
  check (category in ('grammar', 'spelling', 'style', 'element', 'omni'));
