-- =========================================================================
-- Разбор ошибок вернулся к языковой модели — но только разбор.
--
-- Разделение труда теперь такое:
--   * ЧТО игрок сказал неверно — считает поэлементная оценка без модели
--     (_shared/elementScoring.ts). Детерминированно и бесплатно.
--   * ПОЧЕМУ правильно именно так — пишет модель, и только для тех
--     элементов, которые игрок потерял (_shared/explainElements.ts).
--
-- Схеме от этого нужен только один комментарий: у категории element
-- появился текст, которого раньше там намеренно не было.
-- =========================================================================

comment on column grammar_errors.message is
  'Объяснение ошибки. У категории element его пишет модель '
  '(_shared/explainElements.ts) на РОДНОМ языке игрока, цитируя слова '
  'целевого языка в кавычках, и объясняет ПОЧЕМУ правильно так, а не '
  'просто как. Пусто — модель до этого элемента не дошла (лимит разборов '
  'за раунд или сбой провайдера); тогда клиент показывает запасное '
  'пояснение из датасета assets/cefr/explanations_*.txt.';

comment on column grammar_errors.replacement is
  'Правильный вариант. У категории element — текст самого элемента, '
  'который игрок должен был произнести.';
