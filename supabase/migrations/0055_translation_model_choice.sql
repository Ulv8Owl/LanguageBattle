-- ЭТОТ ФАЙЛ ЛЕЖИТ НА ВСЕХ ВЕТКАХ, И ЭТО НАМЕРЕННО. База у веток одна, а
-- supabase db push сверяет папку миграций с историей в базе. Была бы эта
-- миграция только на своей ветке — на любой другой push упирался бы в
-- «в базе есть версии, которых нет в папке».
--
-- =========================================================================
-- Чем переводить расшифровку в «Аудировании» — выбор игрока.
--
-- ЗАЧЕМ ТРЕТЬЯ КОЛОНКА. Шага в разборе теперь два, и делают их разные
-- модели: распознаватель размечает запись по времени, переводчик переводит
-- то, что он услышал. Мерить их надо порознь — иначе не понять, что именно
-- дало разницу: плохая разметка или плохой перевод.
--
-- NULL означает «модель по умолчанию» (её знает сервер). CHECK на список
-- моделей не ставится: ограничение в Postgres умеет только расти, а список
-- для того здесь и появился, чтобы меняться.
-- =========================================================================

alter table users add column if not exists translation_model text;

comment on column users.translation_model is
  'Модель перевода расшифровки в «Аудировании» (qwen-mt-*). NULL — по '
  'умолчанию. Отдельно от listening_model: разметку и перевод меряют порознь.';
