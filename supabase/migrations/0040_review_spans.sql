-- Разбор одной лентой: правильный перевод с вплетёнными ошибками игрока.
--
-- ЧТО БЫЛО. Модель отдавала отдельно свой перевод и отдельно список
-- пропущенных кусков, а приложение искало вторые в первом подстрокой.
-- Поиск промахивался на каждой мелочи — модель цитировала неточно, меняла
-- регистр, — и подсветка молча пропадала. Зачёркивания неверно сказанного
-- не было вовсе: текст игрока нигде не хранился.
--
-- ТЕПЕРЬ границы проводит сама модель. Она возвращает ленту кусков, каждый
-- со своим видом: сказано верно, сказано не так (зачеркнуть), не сказано
-- (красным). Приложению остаётся покрасить, а не догадываться, и балл
-- считается по той же ленте — показать красным одно, а снять баллы за
-- другое стало невозможно по построению.
--
-- Лента лежит в voice_recordings рядом с corrected_text, а не в
-- grammar_errors: это не список ошибок, а разметка ОДНОГО текста, и
-- разбирать её на строки значило бы потерять порядок.

alter table voice_recordings
  add column if not exists review_spans jsonb;

comment on column voice_recordings.review_spans is
  'Разбор ответа одной лентой: [{"k":"ok|bad|miss","t":"..."}]. ok — '
  'сказано верно, bad — сказано не так (зачёркивается, это слова игрока), '
  'miss — не сказано вовсе (красным, это слова правильного перевода). '
  'corrected_text равен склейке всех кусков, кроме bad.';
