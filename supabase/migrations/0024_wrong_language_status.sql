-- Ответ не на том языке перестал притворяться плохим ответом.
--
-- Игрок читал русскую фразу вслух вместо того, чтобы перевести её, а
-- распознавание было ЖЁСТКО заперто в целевом языке: Google обязан выдать
-- текст на заданном языке и физически не может выдать другой. На выходе
-- получался набор английских слов, подобранных по звучанию под русскую
-- речь, — и судья честно разбирал эту бессмыслицу как неудачный перевод,
-- выставляя балл за грамматику несуществующей фразы.
--
-- Теперь родной язык игрока уходит в ASR альтернативой
-- (alternativeLanguageCodes), распознаватель сам сообщает, что он услышал,
-- и такой ответ отсекается ДО судьи. Это заодно экономит игроку те
-- десятки секунд, которые уходили на разбор.
--
--   wrong_language — говорили не на том языке, на который просили
--                    перевести. Судью не звали, балл 1: задание не
--                    выполнено. Клиент показывает репликой хамелеона,
--                    на какой язык надо было перевести.

alter table voice_recordings
  drop constraint if exists voice_recordings_judge_status_check;

alter table voice_recordings
  add constraint voice_recordings_judge_status_check
  check (judge_status in ('pending','ok','degraded','skipped','wrong_language'));
