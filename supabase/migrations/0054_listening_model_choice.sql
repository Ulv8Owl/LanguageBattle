-- ЭТОТ ФАЙЛ ЛЕЖИТ НА ВСЕХ ВЕТКАХ, И ЭТО НАМЕРЕННО. База у веток одна, а
-- supabase db push сверяет папку миграций с историей в базе. Была бы эта
-- миграция только на своей ветке — на любой другой push упирался бы в
-- «в базе есть версии, которых нет в папке». Колонка, которой ветка не
-- пользуется, не стоит ничего; расхождение истории стоит получаса разбора.
--
-- =========================================================================
-- Какой моделью разбирать запись в «Аудировании» — выбор игрока.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ asr_model. Задача другая. В бою распознаётся
-- одна короткая фраза, и от распознавателя нужен только текст. Здесь нужна
-- РАЗМЕТКА ПО ВРЕМЕНИ на всю запись: слово подсвечивается ровно тогда, когда
-- звучит. Мультимодальная модель время не измеряет, а сочиняет — это и
-- показала первая живая проверка: субтитры сильно разъехались со звуком.
-- Померить одно другим можно только переключая модели на одной записи, и
-- смешав два выбора в одну колонку, мы потеряли бы возможность менять их
-- порознь.
--
-- NULL означает «модель по умолчанию» (её знает сервер), поэтому колонка
-- без NOT NULL и без DEFAULT: пустое значение здесь осмысленно.
--
-- CHECK НА СПИСОК МОДЕЛЕЙ НЕ СТАВИТСЯ НАМЕРЕННО. Ограничение в Postgres
-- умеет только расти: убрать из него модель, которая уже кому-то записана,
-- нельзя, а список моделей для того здесь и появился, чтобы меняться.
-- Неизвестное значение сервер сам заменит на модель по умолчанию.
-- =========================================================================

alter table users add column if not exists listening_model text;

comment on column users.listening_model is
  'Модель разбора записи в «Аудировании». NULL — по умолчанию. Отдельно от '
  'asr_model: там нужен текст короткой фразы, здесь — разметка по времени.';
