-- Выбор моделей двухшагового разбора — на игроке, а не на сервере.
--
-- ЗАЧЕМ. Эта ветка существует ради сравнения цены и качества: распознавание
-- плюс текстовый судья против одной мультимодальной модели. Сравнивать надо
-- на ОДНИХ И ТЕХ ЖЕ записях, а переменная окружения этого не позволяет —
-- сменить её значит передеплоить функцию. Колонки в профиле позволяют
-- переключить модель между двумя ответами подряд.
--
-- ДВЕ КОЛОНКИ, А НЕ ОДНА: шага два, и дорожает от них по-разному. За аудио
-- платит только распознавание, судье достаётся текст, и мерить их надо
-- порознь — иначе не понять, что именно дало разницу.
--
-- NULL означает «модель по умолчанию» (её знает сервер), поэтому колонки
-- без NOT NULL и без DEFAULT: пустое значение здесь осмысленно.
--
-- CHECK НА СПИСОК МОДЕЛЕЙ НЕ СТАВИТСЯ НАМЕРЕННО. Ограничение в Postgres
-- умеет только расти: убрать из него модель, которая уже кому-то записана,
-- нельзя, а список моделей для того здесь и появился, чтобы меняться.
-- Неизвестное значение сервер сам заменит на модель по умолчанию.
alter table users add column if not exists asr_model text;
alter table users add column if not exists llm_model text;

comment on column users.asr_model is
  'Модель распознавания речи (qwen-audio-3.0-asr-flash и другие). NULL — по умолчанию.';
comment on column users.llm_model is
  'Текстовая модель-судья (qwen-mt-flash и другие). NULL — по умолчанию.';
