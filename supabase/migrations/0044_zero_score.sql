-- Ноль баллов — законная оценка: в записи нечего разбирать.
--
-- ЧТО БЫЛО. Когда модель отвечала «речи в записи не слышу», воркер считал
-- это своим сбоем и ставил нейтральные семь. На экране это выглядело как
-- оценка за ответ: игрок сказал что-то невнятное и получил больше
-- половины. Разница между «мы не знаем, как он ответил» (наш сбой) и «мы
-- знаем: разбирать нечего» была стёрта.
--
-- Теперь это два разных исхода. Нейтральные семь остаются там, где модель
-- не ответила вовсе — за наш сбой игрока наказывать не за что. А запись,
-- которую модель послушала и речи не разобрала, получает ноль.
--
-- Нижняя граница обеих оценок опускается с единицы до нуля. Единица
-- означала «ответил плохо, но ответил»; для «ответа не было» нужен ноль,
-- иначе минимальную оценку не отличить от плохой.
alter table training_rounds drop constraint if exists training_rounds_final_score_check;
alter table training_rounds
  add constraint training_rounds_final_score_check
  check (final_score between 0 and 10);

alter table round_scores drop constraint if exists round_scores_score_check;
alter table round_scores
  add constraint round_scores_score_check
  check (score between 0 and 10);

comment on column training_rounds.final_score is
  'Балл за раунд по единственной записи, 0..10. Ноль — в записи не '
  'разобрать речи (разбирать было нечего). Нейтральные 7 — наш сбой: '
  'модель не ответила, и как игрок ответил, мы не знаем.';
