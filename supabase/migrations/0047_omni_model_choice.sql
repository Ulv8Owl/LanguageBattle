-- Выбор мультимодальной модели — на игроке, а не на сервере.
--
-- ЗАЧЕМ. Эта ветка существует ради сравнения цены и качества двух моделей
-- на ОДНИХ И ТЕХ ЖЕ записях. Переменная окружения для этого не годится:
-- сменить её значит передеплоить функцию и потерять возможность сказать
-- «вот эта запись разобрана так, а вот эта — иначе». Колонка в профиле
-- позволяет переключиться из настроек между двумя ответами подряд.
--
-- NULL означает «модель по умолчанию» (её знает сервер), поэтому колонка
-- без NOT NULL и без DEFAULT: пустое значение здесь осмысленно.
--
-- CHECK НА СПИСОК МОДЕЛЕЙ НЕ СТАВИТСЯ НАМЕРЕННО. Ограничение в Postgres
-- умеет только расти: убрать из него модель, которая уже кому-то записана,
-- нельзя, а список моделей для того здесь и появился, чтобы меняться.
-- Неизвестное значение сервер сам заменит на модель по умолчанию.
alter table users add column if not exists omni_model text;

comment on column users.omni_model is
  'Мультимодальная модель разбора: qwen3-omni-flash или qwen3.5-omni-flash. NULL — по умолчанию.';
