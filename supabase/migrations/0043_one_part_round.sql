-- Раунд Одиночной Игры состоит из одной части.
--
-- ЧТО БЫЛО. Сначала обе попытки раунда были одной и той же проверкой
-- перевода: игрок делал первую, читал разбор с правильным вариантом — и
-- повторял его во второй. Балл ставился по второй, то есть по тому, что
-- ему только что показали. Потом вторую попытку сделали проверкой
-- произношения. От неё отказались: раунд остаётся одной частью — задание,
-- ответ, разбор, балл.
--
-- Балл за раунд ставится по ЕДИНСТВЕННОЙ записи и лежит, как и раньше, в
-- training_rounds.final_score.
--
-- ЭТА МИГРАЦИЯ УБИРАЕТ СЛЕДЫ ПРОИЗНОШЕНИЯ. Колонок могло и не появиться:
-- предыдущая версия этой миграции падала на CHECK по grammar_errors и
-- откатывалась целиком. Поэтому здесь всё через `if exists` — она обязана
-- отработать и на базе, где этих колонок никогда не было.
alter table voice_recordings drop column if exists judge_mode;
alter table training_rounds drop column if exists pronunciation_score;

comment on column training_rounds.final_score is
  'Балл за раунд по единственной записи. Попытка в раунде одна: вторая '
  'существовала ради обучения, но игрок повторял по ней уже показанный '
  'разбор, и балл получался за память, а не за язык.';

