-- Исправленный вариант ответа игрока целиком: его же слова, но с
-- исправленными ошибками и с добавленными теми, что он пропустил.
--
-- Нужен, чтобы показать правку НАГЛЯДНО: клиент сравнивает распознанный
-- текст с этим вариантом и подсвечивает разницу — что сказано неверно и
-- что пропущено. Списком объяснений это не заменяется: по нему не видно,
-- как должна звучать фраза целиком.
--
-- Отдельный столбец, а не разбор grammar_errors по offset/length: позиции
-- символов LLM возвращает ненадёжно, а целую исправленную строку — вполне.
-- Сравнение по словам на клиенте от кривых offset не зависит.

alter table voice_recordings
  add column if not exists corrected_text text;
