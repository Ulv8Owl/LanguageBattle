/**
 * Уровень CEFR и нейтральный балл — то немногое, что пережило удаление
 * текстового судьи.
 *
 * Раньше это жило в evaluateGrammar.ts вместе с самим судьёй. Судья
 * работал по РАСПОЗНАННОМУ ТЕКСТУ, а распознавания больше нет:
 * мультимодальная модель слышит запись напрямую. Держать файл ради двух
 * определений и называть его «судьёй» значило бы обещать механику,
 * которой нет.
 */

/** Уровень владения: он ограничивает сложность объяснений, не оценку. */
export type CefrLevel = "A1" | "A2" | "B1" | "B2" | "C1" | "C2";

/**
 * Балл, когда оценить не удалось.
 *
 * Семь, а не единица, и это принципиально: единица означает «игрок
 * ответил плохо», а здесь мы просто не знаем, как он ответил. Наказывать
 * за наш сбой нельзя.
 */
export const NEUTRAL_SCORE = 7;

/**
 * Балл, когда в записи нечего разбирать.
 *
 * Ноль, а не нейтральные семь. Разница с NEUTRAL_SCORE в том, ЧЬЯ это
 * неудача: там сбой у нас и мы не знаем, как игрок ответил, — здесь
 * модель послушала доехавшее до неё аудио и речи в нём не нашла.
 * Оценивать нечего, и семь баллов за невнятную запись читались с экрана
 * как «неплохо ответил».
 */
export const SILENT_SCORE = 0;
