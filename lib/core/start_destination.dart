import 'supabase_client.dart';

/// Куда вести игрока после того, как он оказался авторизован.
///
/// Один ответ на весь проект. Раньше этот выбор был написан ДВАЖДЫ — в
/// SplashGate (холодный старт) и в LoginScreen (вход по паролю), — и они
/// разошлись ровно так, как расходятся любые две копии: экран уровня CEFR
/// добавили в SplashGate и забыли в LoginScreen. Дыру было видно не сразу:
/// игрок доходил до выбора уровня, выходил в меню входа, логинился заново —
/// и попадал прямо в игру, ни разу не подтвердив уровень.
///
/// Порядок проверок здесь и есть порядок шагов регистрации, и каждый шаг
/// НЕЛЬЗЯ пропустить, закрыв приложение: пока шаг не пройден, вход в
/// аккаунт приводит игрока обратно на него.
enum StartDestination {
  /// Профиля с языковой парой ещё нет — первый шаг регистрации.
  onboarding('/onboarding'),

  /// Пара есть, но уровень CEFR не подтверждён.
  levelSelect('/level-select'),

  /// Всё пройдено — в игру.
  arena('/arena');

  final String route;
  const StartDestination(this.route);
}

/// Спрашивает у базы, на каком шаге стоит игрок.
///
/// При ошибке (нет сети, пустой ответ) возвращает [StartDestination.onboarding]:
/// повторно пройти онбординг неприятно, но не разрушительно, а вот пустить
/// в игру аккаунт, про который ничего не известно, — хуже.
Future<StartDestination> resolveStartDestination() async {
  try {
    // Спрашиваем именно АКТИВНЫЙ изучаемый язык.
    //
    // Здесь стояло `.limit(1)` без порядка и без фильтра по активности —
    // то есть решение принималось по случайной строке. У языка, начатого
    // позже, placement_done = false (уровень определяют только при
    // регистрации), поэтому у игрока со вторым языком жребий мог выпасть
    // на него: маршрут вёл на экран уровня, а сам экран работает с
    // активным языком, у которого уровень давно определён, и отвечал
    // placement_already_done. Игрок упирался в стену, которую нечем было
    // обойти.
    final active = await supabase
        .from('user_languages')
        .select('id, placement_done')
        .eq('user_id', currentUserId)
        .eq('role', 'learning')
        .eq('is_active', true)
        .maybeSingle();
    if (active != null) {
      // placement_done приходит false у языков, начатых после миграции
      // 0028 и ещё не подтверждённых. Отсутствие поля (старый клиент,
      // урезанная выборка) считаем пройденным: у всех существовавших до
      // 0028 строк миграция проставила true.
      final done = active['placement_done'] as bool? ?? true;
      return done ? StartDestination.arena : StartDestination.levelSelect;
    }

    // Активного языка нет — либо аккаунт совсем новый, либо строки есть,
    // а активной среди них не оказалось. Первое означает онбординг; второе
    // само по себе поломка, но вести из-за неё на онбординг (и заводить
    // язык заново поверх существующих) хуже, чем пустить в игру: языки
    // выбираются в Настройках, и оттуда это чинится одним действием.
    final any = await supabase
        .from('user_languages')
        .select('id')
        .eq('user_id', currentUserId)
        .eq('role', 'learning')
        .limit(1);
    return any.isEmpty ? StartDestination.onboarding : StartDestination.arena;
  } catch (_) {
    return StartDestination.onboarding;
  }
}
