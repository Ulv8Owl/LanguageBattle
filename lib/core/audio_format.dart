/// Единый формат всех голосовых в приложении: WAV (PCM 16 бит), 16 кГц, моно.
///
/// Выбран не ради качества звука, а ради распознавания речи. Раньше запись
/// шла в AAC/m4a, а речь распознавалась прямо на устройстве средствами ОС —
/// от этого пришлось отказаться (запись и системный распознаватель не могут
/// одновременно держать микрофон на Android, транскрипт всегда получался
/// пустым). Теперь речь распознаёт сервер по загруженному файлу, а облачные
/// ASR принимают линейный PCM у всех провайдеров без исключения, тогда как
/// AAC/m4a не принимает, например, Google Cloud Speech-to-Text.
///
/// 16 кГц моно — стандарт для распознавания речи: выше частота не улучшает
/// результат, но утяжеляет загрузку (16 кГц моно это ~32 КБ на секунду).
const int voiceSampleRate = 16000;
const int voiceChannels = 1;
const String voiceFileExtension = 'wav';
const String voiceContentType = 'audio/wav';
