/// Показывать ли техническую панель пайплайна прямо в игре.
///
/// Пока причины сбоев ASR/LLM неясны, отлаживаться по нейтральным 7 баллам
/// невозможно: они выглядят как настоящая оценка и не несут ни одного
/// признака того, что именно сломалось. Панель показывает то, что реально
/// ответили распознавание и судья, — включая сырой ответ модели и текст
/// ошибки.
///
/// Данные берутся из voice_recordings.pipeline_debug (миграция 0016) и
/// собираются в Edge Function.
///
/// ПЕРЕД РЕЛИЗОМ поставить false: игроку эти подробности не нужны, а сырой
/// ответ модели ему видеть незачем.
const bool kShowPipelineDebug = true;

/// Коммит, из которого собрано приложение.
///
/// Подставляется при сборке через --dart-define=BUILD_ID=$(git rev-parse
/// --short HEAD) — это делает tools/build.sh. Руками её выставить нельзя и
/// забыть обновить тоже нельзя: она либо равна коммиту, либо честно
/// сообщает, что собирали в обход скрипта.
///
/// Причина, по которой это вообще есть: трижды подряд «функция не работает»
/// означало «в телефоне не тот APK», и каждый раз это выяснялось только
/// сравнением скриншота с историей git. Метка отвечает на этот вопрос до
/// того, как он задан.
const String kBuildId = String.fromEnvironment(
  'BUILD_ID',
  defaultValue: 'НЕИЗВЕСТЕН — собрано в обход tools/build.sh',
);

/// Человекочитаемая подпись сборки рядом с коммитом.
const String kClientBuild = 'цвета · голосовые · marksOnly';

/// Одна строка для шапки экрана и отладочной панели.
String get kBuildLabel => '$kClientBuild · $kBuildId';
