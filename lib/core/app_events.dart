import 'package:flutter/foundation.dart';

/// Счётчик изменений профиля: рейтинг, лига, языковая пара.
///
/// Экран Арены загружает рейтинг один раз при открытии и живёт в оболочке
/// с сохранением состояния, поэтому возврат на него ничего не перечитывает.
/// Снаружи это выглядело так, будто рейтинг вообще не меняется: полоса
/// лиги стояла на месте после матчей. Тот, кто рейтинг изменил, увеличивает
/// счётчик, а Арена на него подписана.
final ValueNotifier<int> profileRevision = ValueNotifier<int>(0);

void notifyProfileChanged() => profileRevision.value++;
