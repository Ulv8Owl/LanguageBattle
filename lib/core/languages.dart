import 'all_languages.dart';

/// Подписи, связанные с языком задания. Сами языки описаны один раз в
/// all_languages.dart — здесь только фразы вокруг них.
///
/// Раньше тут лежала своя карта названий (languageNames) и своя карта
/// падежей на три языка. Обе переехали в общий реестр: одно место, где
/// заводится язык, вместо пяти, которые надо не забыть.

/// «Переведи на английский:» — подпись к заданию.
///
/// Стоит В НАЧАЛЕ сообщения, а не в конце: это инструкция, что делать с
/// текстом ниже, и прочитать её нужно ДО текста, а не после.
String translateToLabel(String languageCode) {
  final target = allLanguages[languageCode]?.accusative;
  return target != null ? 'Переведи на $target:' : 'Переведи на изучаемый язык:';
}

/// «Распознавание английской речи» — что сейчас делает сервер.
///
/// Отдельное поле [LanguageInfo.speech] («английской речи», «речи на
/// хинди») вместо склонения на лету: у несклоняемых названий — хинди,
/// урду, иврит — прилагательного нет вовсе, и любая формула вида
/// «<название>ой речи» на них ломается. Готовая форма на каждый язык
/// пишется один раз и читается правильно всегда.
String recognisingSpeechLabel(String targetLanguage) {
  final speech = allLanguages[targetLanguage]?.speech;
  return speech != null ? 'Распознавание $speech' : 'Распознавание речи';
}
