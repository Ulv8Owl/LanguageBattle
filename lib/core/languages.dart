/// Названия языков для интерфейса.
///
/// Фраза раунда показывается на РОДНОМ языке игрока, а произнести её нужно
/// на изучаемом — то есть задание в том, чтобы перевести вслух. Без явной
/// подписи это неочевидно: на экране просто текст, и непонятно, повторить
/// его или перевести.
const languageNames = {
  'en': 'English',
  'es': 'Español',
  'ru': 'Русский',
};

/// «Скажи это по-английски» — предложный оборот, а не название языка:
/// в подписи к заданию он читается естественнее.
String speakInLabel(String languageCode) {
  const adverbs = {
    'en': 'по-английски',
    'es': 'по-испански',
    'ru': 'по-русски',
  };
  final adverb = adverbs[languageCode];
  return adverb != null ? 'Скажи это $adverb' : 'Скажи это на изучаемом языке';
}
