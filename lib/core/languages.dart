/// Названия языков для интерфейса.
///
/// Фраза раунда показывается на РОДНОМ языке игрока, а произнести её нужно
/// на изучаемом — то есть задание в том, чтобы перевести вслух. Без явной
/// подписи это неочевидно: на экране просто текст, и непонятно, повторить
/// его или перевести.
const languageNames = {
  'en': 'English',
  'es': 'Español',
  'ru': 'Русский',
};

/// «Переведи на английский:» — подпись к заданию.
///
/// Стоит В НАЧАЛЕ сообщения, а не в конце: это инструкция, что делать с
/// текстом ниже, и прочитать её нужно ДО текста, а не после.
String translateToLabel(String languageCode) {
  const targets = {
    'en': 'английский',
    'es': 'испанский',
    'ru': 'русский',
  };
  final target = targets[languageCode];
  return target != null ? 'Переведи на $target:' : 'Переведи на изучаемый язык:';
}
