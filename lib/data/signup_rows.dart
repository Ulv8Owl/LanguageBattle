/// Строки user_languages, создаваемые при заполнении профиля.
///
/// Вынесено из экрана ради одного-единственного свойства, которое иначе
/// проверить нечем: у всех строк групповой вставки набор ключей ОБЯЗАН
/// совпадать.
///
/// PostgREST на групповой вставке строит один список столбцов из объединения
/// ключей всех объектов и подставляет явный NULL там, где в объекте ключа
/// нет, — а вовсе не значение по умолчанию из схемы. Один пропущенный
/// is_active в родной строке (в схеме `not null default false`) ронял
/// регистрацию каждого нового игрока на самом первом экране, и по коду это
/// не бросалось в глаза: строки выглядели просто «немного разными».
///
/// Рейтинговых столбцов здесь нет намеренно. rating заводит схема (600 —
/// public.elo_default_rating(), середина Олова), а elo, league_rating,
/// league и cefr_level считает по нему триггер trg_sync_rating_mirrors
/// (миграция 0026). Прислать их отсюда значило бы прислать числа, которые
/// тут же будут перезаписаны.
///
/// Настоящий стартовый рейтинг игрок получает не здесь, а на экране
/// выбора уровня CEFR после проверки навыка — RPC set_placement_rating
/// (миграция 0028).
List<Map<String, dynamic>> signupLanguageRows({
  required String userId,
  required String nativeLanguage,
  required String targetLanguage,
}) =>
    [
      {
        'user_id': userId,
        'language_code': nativeLanguage,
        'role': 'native',
        // У родной строки native_for нет смысла: она и есть родной язык.
        // Ключ всё равно нужен — PostgREST на групповой вставке строит
        // один список столбцов из объединения ключей всех объектов, и
        // пропуск здесь превратился бы в явный NULL там, где схема ждёт
        // значение (эта же ловушка когда-то роняла регистрацию из-за
        // is_active).
        'native_for': null,
        // Активна всегда изучаемая пара, не родной язык.
        'is_active': false,
      },
      {
        'user_id': userId,
        'language_code': targetLanguage,
        'role': 'learning',
        // native_for — родной язык ИМЕННО этой пары. Без него первая пара
        // аккаунта оставалась с null, а весь клиент читает
        // `native_for ?? users.native_language`: пока главный родной не
        // меняли, подмены не было видно, но стоило сменить русский на
        // английский — и пара ru-en превращалась в en-en, то есть язык
        // становился сам себе родным. Пара обязана помнить, с какого
        // языка её учат, с первой же секунды.
        'native_for': nativeLanguage,
        'is_active': true,
      },
    ];
