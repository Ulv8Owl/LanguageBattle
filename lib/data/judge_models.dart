import '../core/supabase_client.dart';

/// Какой моделью разбирается запись — выбор игрока, а не сервера.
///
/// ЗАЧЕМ ЭТО ЕСТЬ. Ветка Omni существует ради одного вопроса: что дороже и
/// что лучше на ОДНИХ И ТЕХ ЖЕ записях. Ответить на него можно, только
/// переключая модель между двумя ответами подряд, — переменная окружения на
/// сервере для этого не годится, её смена это передеплой функции.
///
/// ЧТО ЗДЕСЬ НЕ ХРАНИТСЯ. Ключ провайдера. Он живёт только в секретах Edge
/// Function; клиент вообще не разговаривает с моделью — он лишь записывает
/// в свой профиль, какую модель просить.
library;

/// Модели, между которыми можно переключаться. Первая — по умолчанию.
///
/// Тот же список продублирован на сервере (`OMNI_MODELS` в omniJudge.ts), и
/// это не забытая копия: значение из профиля — ввод снаружи, и проверять
/// его надо там, где им пользуются. Здесь список решает, что показать в
/// настройках; там — что можно отправить провайдеру.
const List<String> omniModels = ['qwen3-omni-flash', 'qwen3.5-omni-flash'];

/// Модель по умолчанию: её же подставит сервер, если в профиле пусто.
String get defaultOmniModel => omniModels.first;

/// Что выбрано у игрока. Пусто или неизвестное значение — модель по
/// умолчанию: список моделей меняется, а в профиле может лежать вчерашнее.
Future<String> fetchOmniModel() async {
  final row = await supabase
      .from('users')
      .select('omni_model')
      .eq('id', currentUserId)
      .maybeSingle();
  final saved = (row?['omni_model'] as String?)?.trim() ?? '';
  return omniModels.contains(saved) ? saved : defaultOmniModel;
}

/// Сохраняет выбор. Дальше его прочитает воркер на следующей же записи.
Future<void> saveOmniModel(String model) => supabase
    .from('users')
    .update({'omni_model': model})
    .eq('id', currentUserId);
