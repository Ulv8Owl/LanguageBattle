/// Текстовые модели-судьи. Первая — по умолчанию.
///
/// ПОРЯДОК НЕ АЛФАВИТНЫЙ И НЕ СЛУЧАЙНЫЙ. Обычные чат-модели идут первыми,
/// `qwen-mt-*` — последними: это переводчики, а не собеседники, и свободный
/// ответ по инструкции (тем более JSON) может быть им не по профилю. Пока
/// такая модель стояла первой, ветка из коробки выглядела сломанной, хотя
/// дело было только в выборе по умолчанию.
///
/// Из списка их не убрали: смысл ветки в том и есть, чтобы померить. Модель,
