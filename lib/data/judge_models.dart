/// провайдера (у каждого семейства своя форма запроса), но проверены пока
/// только на форме; по умолчанию ветка должна работать, а не проверяться.
///
/// ЧЕГО В СПИСКЕ НЕТ И ПОЧЕМУ. `fun-asr-mtl`, `fun-asr` и `*-filetrans`
/// живут на отдельном асинхронном пути распознавания файлов: там задача
/// ставится в очередь и опрашивается, это другой адрес и другой сценарий.
/// Пока мы туда не ходим, держать их здесь значит показывать игроку кнопку,
