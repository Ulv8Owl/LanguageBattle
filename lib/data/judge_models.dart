/// Какими моделями разбирается запись — выбор игрока, а не сервера.
///
/// ЗАЧЕМ ЭТО ЕСТЬ. Ветка LLM существует ради одного вопроса: что дороже и
/// что лучше — распознавание плюс текстовый судья или одна мультимодальная
/// модель. Ответить можно, только переключая модели между ответами подряд;
/// переменная окружения на сервере для этого не годится, её смена это
/// передеплой функции.
///
/// ПОЧЕМУ ДВА СПИСКА, А НЕ ОДИН. Шага два, и дорожают они по-разному: за
/// аудио платит только распознавание, судье достаётся текст. Мерить их надо
/// порознь, иначе не понять, что именно дало разницу.
///
/// ЧТО ЗДЕСЬ НЕ ХРАНИТСЯ. Ключ провайдера. Он живёт только в секретах Edge
/// Function; клиент вообще не разговаривает с моделями — он лишь записывает
/// в свой профиль, какие модели просить.
library;

import '../core/supabase_client.dart';

/// Модели для первого шага — превратить речь в текст. Первая по умолчанию.
///
/// ПЕРВЫМИ СТОЯТ МУЛЬТИМОДАЛЬНЫЕ, И ЭТО НЕ ОПЕЧАТКА. Они не заточены под
/// распознавание и стоят дороже — зато они работают. Специальные модели
/// распознавания у этого провайдера через доступные нам схемы вызова не
/// зовутся вовсе: тело запроса у нас побайтово такое же, как у рабочего
/// вызова на ветке Omni, отличается ровно имя модели, — и они всё равно
/// отвечают отказом. Держать ветку сломанной ради экономии, которой пока
/// нет, нельзя: она сначала должна работать.
///
/// Из списка их не убрали: как только станет известна нужная форма вызова,
/// вернуть экономию будет делом одного переключателя.
const List<String> asrModels = [
