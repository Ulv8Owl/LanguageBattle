/// Какими моделями разбирается запись — выбор игрока, а не сервера.
///
/// ЗАЧЕМ ЭТО ЕСТЬ. Ветка LLM существует ради одного вопроса: что дороже и
/// что лучше — распознавание плюс текстовый судья или одна мультимодальная
/// модель. Ответить можно, только переключая модели между ответами подряд;
/// переменная окружения на сервере для этого не годится, её смена это
/// передеплой функции.
///
/// ПОЧЕМУ ДВА СПИСКА, А НЕ ОДИН. Шага два, и дорожают они по-разному: за
/// аудио платит только распознавание, судье достаётся текст. Мерить их надо
/// порознь, иначе не понять, что именно дало разницу.
///
/// ЧТО ЗДЕСЬ НЕ ХРАНИТСЯ. Ключ провайдера. Он живёт только в секретах Edge
/// Function; клиент вообще не разговаривает с моделями — он лишь записывает
/// в свой профиль, какие модели просить.
library;

import '../core/supabase_client.dart';

/// Модели распознавания. Первая — по умолчанию.
///
/// Порядок тот, в котором их назвал владелец проекта. Тот же список
/// продублирован на сервере (`ASR_MODELS` в asr.ts), и это не забытая копия:
/// значение из профиля — ввод снаружи, и проверять его надо там, где им
/// пользуются.
///
/// ПРО `-filetrans`: у провайдера это отдельная, асинхронная схема вызова
/// (ссылка на файл вместо вложенного аудио). Сервер зовёт их так же, как
/// остальные, — то есть они могут ответить ошибкой. Это видно в отладке
/// записи, и по настоящему тексту ошибки дописать вторую схему быстрее, чем
/// угадывать её заранее.
const List<String> asrModels = [
  'qwen-audio-3.0-asr-flash',
  'qwen-audio-3.0-asr-flash-filetrans',
  'fun-asr-mtl',
  'qwen3-asr-flash',
  'qwen3-asr-flash-filetrans',
  'fun-asr-flash-2026-06-15',
];

/// Текстовые модели-судьи. Первая — по умолчанию.
///
/// ПРО `qwen-mt-*`: это переводчики, а не собеседники, и свободный ответ по
/// инструкции — тем более JSON — может быть им не по профилю. Список
/// оставлен таким, как заказан: смысл ветки в том и есть, чтобы померить это
/// на живых записях. Модель, не вернувшая JSON, честно превращается в
/// «модель не ответила» и балл игроку не портит.
const List<String> llmModels = [
  'qwen-mt-flash',
  'kimi-k3',
  'deepseek-v4-pro-0813',
  'glm-5.2',
  'qwen-mt-lite',
  'qwen-mt-turbo',
  'qwen-mt-plus',
];

String get defaultAsrModel => asrModels.first;
String get defaultLlmModel => llmModels.first;

/// Что выбрано у игрока. Пусто или неизвестное значение — модель по
/// умолчанию: список моделей меняется, а в профиле может лежать вчерашнее.
Future<({String asr, String llm})> fetchJudgeModels() async {
  final row = await supabase
      .from('users')
      .select('asr_model, llm_model')
      .eq('id', currentUserId)
      .maybeSingle();
  final asr = (row?['asr_model'] as String?)?.trim() ?? '';
  final llm = (row?['llm_model'] as String?)?.trim() ?? '';
  return (
    asr: asrModels.contains(asr) ? asr : defaultAsrModel,
    llm: llmModels.contains(llm) ? llm : defaultLlmModel,
  );
}

/// Сохраняет выбор распознавателя. Прочитает его воркер на следующей записи.
Future<void> saveAsrModel(String model) => supabase
    .from('users')
    .update({'asr_model': model})
    .eq('id', currentUserId);

/// Сохраняет выбор судьи.
Future<void> saveLlmModel(String model) => supabase
    .from('users')
    .update({'llm_model': model})
    .eq('id', currentUserId);
