  'qwen3.5-omni-flash',
  // Не отвечают ни на одну из трёх известных форм вызова.
  'qwen-audio-3.0-asr-flash',
  'qwen-audio-3.0-asr-flash-filetrans',
  'fun-asr-mtl',
  'qwen3-asr-flash',
  'qwen3-asr-flash-filetrans',
